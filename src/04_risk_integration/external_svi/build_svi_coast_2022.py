import pandas as pd
import requests
from unidecode import unidecode

arquivo = "/content/drive/MyDrive/OSR11/municipios_extraidos.xlsx"

df = pd.read_excel(arquivo)

# garantir nomes das colunas
df.columns = ["municipio", "uf"]

def limpar_nome(x):
    return unidecode(str(x).upper().strip())

df["municipio_limpo"] = df["municipio"].apply(limpar_nome)
df["uf"] = df["uf"].astype(str).str.upper().str.strip()

# baixar municípios do IBGE
url = "https://servicodados.ibge.gov.br/api/v1/localidades/municipios"
dados = requests.get(url).json()

ibge = pd.json_normalize(dados)

ibge_base = pd.DataFrame({
    "cod_ibge": ibge["id"].astype(str),
    "municipio_ibge": ibge["nome"],
    "municipio_limpo": ibge["nome"].apply(limpar_nome),
    "uf": ibge["microrregiao.mesorregiao.UF.sigla"]
})

# cruzar por município + UF
resultado = df.merge(
    ibge_base[["cod_ibge", "municipio_limpo", "uf"]],
    on=["municipio_limpo", "uf"],
    how="left"
)

# organizar colunas
resultado = resultado[["municipio", "uf", "cod_ibge"]]

