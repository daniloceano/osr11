# CARREGAR BASE
# =========================
base = pd.read_excel(arquivo)

base["cod_ibge"] = base["cod_ibge"].astype(str)

# remover coluna antiga
base = base.drop(columns=["pop_poverty"], errors="ignore")

# =========================
# MUNICÍPIOS
# =========================
codigos = ",".join(base["cod_ibge"].tolist())

# =========================
# URL SIDRA
# =========================
url_renda = f"https://apisidra.ibge.gov.br/values/t/10296/n6/{codigos}/v/13604/p/2022/c386/all/c2/6794/c86/95251?formato=json"

res = requests.get(url_renda)

print(res.status_code)

# =========================
# JSON → DATAFRAME
# =========================
data = res.json()

renda = pd.DataFrame(data)

renda.columns = renda.iloc[0]

renda = renda.iloc[1:].copy()

renda["Valor"] = pd.to_numeric(renda["Valor"], errors="coerce")

# =========================
# TOTAL
# =========================
total = renda[
    renda["Classes de rendimento nominal mensal domiciliar per capita"] == "Total"
][["Município (Código)", "Valor"]]

total = total.rename(columns={"Valor": "valor_total"})

# =========================
# BAIXA RENDA
# Até 1/2 salário mínimo
# =========================
baixa = renda[
    renda["Classes de rendimento nominal mensal domiciliar per capita"].isin([
        "Até 1/4 de salário mínimo",
        "Mais de 1/4 a 1/2 salário mínimo"
    ])
]

baixa = baixa.groupby("Município (Código)", as_index=False)["Valor"].sum()

baixa = baixa.rename(columns={"Valor": "valor_baixa"})

# =========================
# MERGE
# =========================
df_renda = total.merge(
    baixa,
    on="Município (Código)",
    how="left"
)

df_renda["valor_baixa"] = df_renda["valor_baixa"].fillna(0)

# =========================
# CÁLCULO
# =========================
df_renda["pop_poverty"] = (
    df_renda["valor_baixa"] / df_renda["valor_total"]
)

# =========================
# AJUSTAR
# =========================
df_renda = df_renda[["Município (Código)", "pop_poverty"]]

df_renda.columns = ["cod_ibge", "pop_poverty"]

df_renda["cod_ibge"] = df_renda["cod_ibge"].astype(str)

# =========================
# MERGE FINAL
# =========================
base = base.merge(
    df_renda,
    on="cod_ibge",
    how="left"
)

# remover duplicados
base = base.drop_duplicates(subset=["cod_ibge"])

# =========================
# SALVAR
# =========================
base.to_excel(arquivo, index=False)

